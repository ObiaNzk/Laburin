CREATE TYPE user_role AS ENUM ('CANDIDATE', 'BUSINESS');
CREATE TYPE offer_category AS ENUM ('GASTRONOMY', 'MECHANICS', 'STOCK', 'CLOTHING');
CREATE TYPE offer_status AS ENUM ('ACTIVE', 'CLOSED');
CREATE TYPE salary_period AS ENUM ('HOUR', 'DAY', 'MONTH');
CREATE TYPE application_status AS ENUM ('SENT', 'APPROVED', 'REJECTED');

CREATE TABLE users (
    id            uuid PRIMARY KEY,
    role          user_role   NOT NULL,
    email         text        NOT NULL,
    password_hash text        NOT NULL,
    display_name  text        NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now()
);
-- Emails are stored lowercased by the service; the index makes uniqueness case-insensitive anyway.
CREATE UNIQUE INDEX users_email_key ON users (lower(email));

CREATE TABLE businesses (
    user_id   uuid PRIMARY KEY REFERENCES users (id),
    name      text             NOT NULL,
    category  offer_category   NOT NULL,
    schedule  text             NOT NULL,
    address   text             NOT NULL,
    latitude  double precision NOT NULL,
    longitude double precision NOT NULL
);

-- The id is generated by the app so a retried publish is idempotent.
CREATE TABLE offers (
    id            uuid PRIMARY KEY,
    business_id   uuid           NOT NULL REFERENCES businesses (user_id),
    title         text           NOT NULL,
    category      offer_category NOT NULL,
    schedule      text           NOT NULL,
    description   text           NOT NULL,
    job_type      text           NOT NULL DEFAULT '',
    salary_min    bigint,
    salary_max    bigint,
    salary_period salary_period,
    status        offer_status   NOT NULL DEFAULT 'ACTIVE',
    created_at    timestamptz    NOT NULL DEFAULT now(),
    updated_at    timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT offers_salary_check CHECK (
        (salary_min IS NULL AND salary_max IS NULL AND salary_period IS NULL)
        OR (salary_min > 0 AND salary_period IS NOT NULL AND (salary_max IS NULL OR salary_max > salary_min))
    )
);
CREATE INDEX offers_business_id_idx ON offers (business_id);

-- The id is generated by the app so a retried application is idempotent.
CREATE TABLE applications (
    id           uuid PRIMARY KEY,
    offer_id     uuid               NOT NULL REFERENCES offers (id),
    candidate_id uuid               NOT NULL REFERENCES users (id),
    status       application_status NOT NULL DEFAULT 'SENT',
    created_at   timestamptz        NOT NULL DEFAULT now(),
    reviewed_at  timestamptz,
    CONSTRAINT applications_offer_candidate_key UNIQUE (offer_id, candidate_id)
);
CREATE INDEX applications_candidate_id_idx ON applications (candidate_id);

CREATE TABLE cvs (
    user_id     uuid PRIMARY KEY REFERENCES users (id),
    file_name   text        NOT NULL,
    content     bytea       NOT NULL,
    uploaded_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE push_tokens (
    token      text PRIMARY KEY,
    user_id    uuid        NOT NULL REFERENCES users (id),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX push_tokens_user_id_idx ON push_tokens (user_id);

